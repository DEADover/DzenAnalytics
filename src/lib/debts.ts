import type { Transaction } from "../types";

/**
 * Долги по людям — то, чего нет в самом Дзен-мани.
 *
 * Дзен держит ОДИН счёт «Долги» на пользователя: сколько всего должны вам и
 * сколько должны вы, свалено в один остаток. Кто именно за этим стоит, лежит в
 * самой операции — в поле «Контрагент» (`payee`); сервер Дзен-мани без него
 * долговую операцию не принимает вовсе. Значит разложить остаток по людям
 * можно, и это ровно то, чего от списка счетов ждут: «кому я должен и кто мне».
 *
 * Знак — со стороны пользователя:
 *   • деньги ушли НА долговой счёт  → вы дали в долг (или закрыли свой долг);
 *   • деньги ушли СО долгового счёта → вам вернули (или вы взяли в долг).
 * Сумма по контрагенту больше нуля — должны вам, меньше — должны вы.
 *
 * Итог по всем контрагентам сходится с остатком счёта НЕ ВСЕГДА: разбивка
 * складывается из операций, а остаток счёта живёт своей жизнью. Расхождение
 * даёт начальный остаток, операции старше загруженной истории и курсовая
 * разница. Считает его `unallocatedDebt` — чтобы страница показала разницу, а
 * не молчала о ней.
 */

/** Свод по одному контрагенту. Суммы — в базовой валюте. */
export interface DebtCounterparty {
  /** Имя контрагента; пусто — операция без него (в Дзен-мани так не бывает,
   *  но данные приезжают и из CSV). Написание — самое частое из встреченных. */
  payee: string;
  /** По чему собран: имя без регистра и лишних пробелов. По нему же потом
   *  отбираются операции контрагента — иначе клик по строке нашёл бы лишь
   *  одно написание из нескольких. */
  key: string;
  /** Итог: больше нуля — должны вам, меньше — должны вы. */
  amount: number;
  /** Сколько всего ушло в долг (или на погашение своего долга). */
  out: number;
  /** Сколько всего вернулось (или пришло в долг вам). */
  back: number;
  count: number;
  /** Дата последней операции — по ней видно, насколько долг «живой». */
  last: string;
  /** Рассчитались: итог нулевой (с точностью до копейки). */
  settled: boolean;
}

export interface DebtBreakdown {
  rows: DebtCounterparty[];
  /** Сумма по всем контрагентам. С остатком счёта сходится не всегда —
   *  см. `unallocatedDebt`. */
  total: number;
  /** Сколько всего должны вам и сколько должны вы (по модулю). */
  owedToYou: number;
  owedByYou: number;
}

/** Меньше половины копейки — это ноль: после пересчёта по курсу дня в суммах
 *  остаются хвосты, и «рассчитались» не должно зависеть от них. */
const EPS = 0.005;

/** Название контрагента для показа, когда его нет. */
export const NO_COUNTERPARTY = "Без контрагента";

/**
 * Ключ контрагента: имя без регистра и без лишних пробелов.
 *
 * «OZON» и «Ozon» — один и тот же магазин, а у нас они расходились по двум
 * строкам: одному «должны вы» 874 ₽, другому «должны вам» те же 874 ₽. В
 * Дзен-мани такая пара схлопывается в ноль и из списка уходит, а у нас висела
 * выдуманным долгом в обе стороны (issue #80).
 *
 * Складываем только то, что различается ОДНИМ регистром и пробелами: это
 * заведомо одно имя. Похожие, но разные написания («Ozon» и «Озон») здесь не
 * трогаем — для них есть общая группировка контрагентов, и решать за человека,
 * что это один и тот же, страница счетов не должна.
 */
export function debtPayeeKey(payee: string): string {
  return payee.trim().replace(/\s+/g, " ").toLocaleLowerCase("ru");
}

/**
 * Разложить долговые операции по контрагентам.
 *
 * `debtAccounts` — названия счетов типа «Долги»: в Дзен-мани он один, но
 * ограничивать себя одним нельзя — счёт можно переименовать, а в CSV их может
 * оказаться несколько.
 */
export function debtsByCounterparty(
  transactions: Transaction[],
  debtAccounts: Set<string>
): DebtBreakdown {
  const acc = new Map<string, DebtCounterparty>();
  /** Написания имени внутри одного ключа и сколько раз каждое встретилось. */
  const spellings = new Map<string, Map<string, number>>();

  for (const t of transactions) {
    const into = !!t.incomeAccount && debtAccounts.has(t.incomeAccount);
    const from = !!t.outcomeAccount && debtAccounts.has(t.outcomeAccount);
    // Перевод внутри долговых счетов сам себе не долг: он ничего не меняет ни
    // для вас, ни для контрагента.
    if (into === from) continue;
    const amount = into ? t.amountBase : -t.amountBase;
    const payee = (t.payee || "").trim() || NO_COUNTERPARTY;
    const key = debtPayeeKey(payee);

    let row = acc.get(key);
    if (!row) {
      row = { payee, key, amount: 0, out: 0, back: 0, count: 0, last: "", settled: true };
      acc.set(key, row);
    }
    // Показываем то написание, которое встречается чаще: в «OZON» против
    // «Ozon» побеждает то, что человек видит в выписке чаще всего.
    const seen = (spellings.get(key) ?? new Map<string, number>()).set(
      payee,
      (spellings.get(key)?.get(payee) ?? 0) + 1
    );
    spellings.set(key, seen);
    row.amount += amount;
    if (into) row.out += t.amountBase;
    else row.back += t.amountBase;
    row.count++;
    if (t.date > row.last) row.last = t.date;
  }

  let total = 0;
  let owedToYou = 0;
  let owedByYou = 0;
  for (const row of acc.values()) {
    const variants = spellings.get(row.key);
    if (variants && variants.size > 1) {
      // При равной частоте — то, что раньше по алфавиту: любой выбор годится,
      // лишь бы он не прыгал от порядка операций.
      row.payee = [...variants.entries()].sort(
        (a, b) => b[1] - a[1] || a[0].localeCompare(b[0], "ru")
      )[0][0];
    }
    row.settled = Math.abs(row.amount) < EPS;
    total += row.amount;
    if (row.amount >= EPS) owedToYou += row.amount;
    else if (row.amount <= -EPS) owedByYou += -row.amount;
  }

  // Сначала непогашенные — по величине, потом рассчитавшиеся по дате: список
  // отвечает на вопрос «с кем сейчас не рассчитались», а история идёт следом.
  const rows = [...acc.values()].sort(
    (a, b) =>
      Number(a.settled) - Number(b.settled) ||
      Math.abs(b.amount) - Math.abs(a.amount) ||
      b.last.localeCompare(a.last)
  );

  return { rows, total, owedToYou, owedByYou };
}

/**
 * Порог, ниже которого расхождение — шум, а не факт.
 *
 * Одна единица базовой валюты: суммы операций пересчитаны по курсу ЦБ на их
 * дату, а остаток счёта — по сегодняшнему, и копеечные хвосты неизбежны.
 * Показывать из-за них строку «не разложено 0 ₽» было бы хуже, чем молчать.
 */
export const DEBT_GAP_MIN = 1;

/**
 * Сколько остатка долгового счёта не легло ни на одного контрагента.
 *
 * Разбивка собирается ИЗ ОПЕРАЦИЙ, а остаток счёта приходит из Дзен-мани целым
 * числом, и совпадать они обязаны не всегда. Расходятся они по трём причинам, и
 * все три — не ошибка:
 *
 *   • начальный остаток счёта: история началась с уже существующего долга;
 *   • операции старше загруженной истории — их в разбивке просто нет;
 *   • курсовая разница у валютного долга: операция пересчитана по курсу своего
 *     дня, а остаток счёта — по сегодняшнему.
 *
 * Раньше разница нигде не показывалась, и человек видел только то, что наша
 * сумма не сходится с Дзен-мани (issue #80). Ноль — сверять не с чем либо
 * расхождение в пределах округления.
 */
export function unallocatedDebt(
  balanceBase: number | null | undefined,
  breakdown: DebtBreakdown | null | undefined
): number {
  if (balanceBase == null || !breakdown) return 0;
  const gap = balanceBase - breakdown.total;
  return Math.abs(gap) < DEBT_GAP_MIN ? 0 : gap;
}
