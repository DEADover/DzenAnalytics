import { describe, it, expect } from "vitest";
import {
  planHashtagRename,
  renameHashtagInComment,
  rulesMentioningHashtag,
} from "./hashtagRename";
import { extractHashtags, groupByHashtag } from "./aggregations";
import type { Transaction } from "../types";

const rn = renameHashtagInComment;

describe("renameHashtagInComment: переименование", () => {
  it("меняет тег и не трогает остальной текст", () => {
    expect(rn("оплата #налоги за март", "налоги", "Налоги")).toBe(
      "оплата #Налоги за март"
    );
  });

  it("переименование, отличающееся только регистром, — полноценная правка", () => {
    // Регистронезависимое сравнение здесь сказало бы «менять нечего».
    expect(rn("#налоги", "налоги", "Налоги")).toBe("#Налоги");
  });

  it("не задевает тег, для которого наш — лишь префикс", () => {
    expect(rn("Платёж #налог и годовой #налоги", "налог", "сборы")).toBe(
      "Платёж #сборы и годовой #налоги"
    );
  });

  it("не задевает тег с хвостовым дефисом — это другой тег", () => {
    expect(extractHashtags("сумма #налоги-")).toEqual(["налоги-"]);
    expect(rn("сумма #налоги-", "налоги", "Налоги")).toBe("сумма #налоги-");
  });

  it("правит вхождения без левой границы — их видит и разбор", () => {
    // У HASHTAG_RE нет левой границы: «оплата#налоги» — тег. Пропусти мы их,
    // таблица тегов продолжила бы показывать старое имя.
    expect(rn("оплата#налоги и ссылка /#налоги", "налоги", "Налоги")).toBe(
      "оплата#Налоги и ссылка /#Налоги"
    );
  });

  it("комментарий без нашего тега не меняется вовсе", () => {
    expect(rn("просто текст", "налоги", "Налоги")).toBe("просто текст");
    expect(rn("", "налоги", "Налоги")).toBe("");
  });

  it("переименование в себя — не операция", () => {
    expect(rn("#налоги", "налоги", "налоги")).toBe("#налоги");
  });

  it("тег из одних цифр и с дефисом внутри тоже переименовывается", () => {
    expect(rn("отчёт #налоги-2024", "налоги-2024", "Налоги2024")).toBe(
      "отчёт #Налоги2024"
    );
  });
});

describe("renameHashtagInComment: перенос не создаёт дубля", () => {
  it("переименование повтора сохраняет оба вхождения", () => {
    // Удалять при простом переименовании нечего: структуру комментария не
    // трогаем, даже если тег в нём повторяется.
    expect(rn("#налоги за квартал #налоги", "налоги", "Налоги")).toBe(
      "#Налоги за квартал #Налоги"
    );
  });

  it("перенос повтора не оставляет двух целевых тегов", () => {
    expect(rn("#налоги за квартал #налоги #бюджет", "налоги", "бюджет")).toBe(
      "за квартал #бюджет"
    );
  });

  it("перенос в тег, который уже есть рядом, не плодит дубль", () => {
    expect(rn("аренда #налоги #бюджет", "налоги", "бюджет")).toBe(
      "аренда #бюджет"
    );
  });

  it("целевой тег стоит раньше — сохраняется его место", () => {
    expect(rn("#бюджет аренда #налоги", "налоги", "бюджет")).toBe(
      "#бюджет аренда"
    );
  });

  it("обе формы регистра в одном комментарии сливаются в одну", () => {
    expect(rn("#налоги #Налоги", "налоги", "Налоги")).toBe("#Налоги");
  });

  it("комментарий, где есть только целевой тег, не трогаем", () => {
    expect(rn("аренда #бюджет", "налоги", "бюджет")).toBe("аренда #бюджет");
  });
});

describe("renameHashtagInComment: мусор после удаления", () => {
  it("не оставляет двойной пробел", () => {
    expect(rn("аренда #налоги #бюджет за март", "налоги", "бюджет")).toBe(
      "аренда #бюджет за март"
    );
  });

  it("не оставляет ведущий пробел", () => {
    expect(rn("#налоги #бюджет", "налоги", "бюджет")).toBe("#бюджет");
  });

  it("не оставляет хвостовой пробел", () => {
    expect(rn("аренда #бюджет #налоги", "налоги", "бюджет")).toBe(
      "аренда #бюджет"
    );
  });

  it("убирает висящую запятую", () => {
    expect(rn("#налоги, #бюджет", "налоги", "бюджет")).toBe("#бюджет");
    expect(rn("аренда #бюджет, #налоги", "налоги", "бюджет")).toBe(
      "аренда #бюджет"
    );
  });

  it("уносит строку целиком, но чужие переносы не трогает", () => {
    expect(rn("аренда\n#налоги\n#бюджет", "налоги", "бюджет")).toBe(
      "аренда\n#бюджет"
    );
    expect(rn("#бюджет\n#налоги\nитого", "налоги", "бюджет")).toBe(
      "#бюджет\nитого"
    );
  });

  it("комментарий из одного тега после переноса становится пустым", () => {
    // Пустая строка, а не пробел: ниже по конвейеру пустой комментарий уедет
    // в облако как null, а строка из пробела осталась бы мусором.
    expect(rn("#налоги", "налоги", "бюджет")).toBe("#бюджет");
  });
});

/** Операция-заглушка: нам важны только id, kind и комментарий. */
function tx(id: string, comment: string, kind: Transaction["kind"] = "expense"): Transaction {
  return {
    id,
    date: "2026-08-01",
    category: "Еда",
    subcategory: null,
    categoryFull: "Еда",
    payee: "Магазин",
    comment,
    amount: 100,
    amountBase: 100,
    currency: "RUB",
    account: "Карта",
    kind,
  } as Transaction;
}

describe("planHashtagRename", () => {
  it("берёт только операции, где комментарий реально изменится", () => {
    const plan = planHashtagRename(
      [tx("1", "обед #налоги"), tx("2", "обед без тега"), tx("3", "#налоги-2024")],
      "налоги",
      "Налоги"
    );
    expect(plan.rows.map((r) => r.id)).toEqual(["1"]);
    expect(plan.rows[0].after).toBe("обед #Налоги");
  });

  it("переводы переписывает наравне с остальными", () => {
    // Раньше их приходилось пропускать: отправка правки пересобирала обе ноги
    // и обнуляла получателя. Теперь неструктурная правка патчит строку из
    // кэша на месте, и переводы безопасны.
    const plan = planHashtagRename(
      [tx("1", "#налоги"), tx("2", "#налоги", "transfer")],
      "налоги",
      "Налоги"
    );
    expect(plan.rows.map((r) => r.id)).toEqual(["1", "2"]);
  });

  it("долговые операции пропускает — они опасны по типу счёта, а не по виду", () => {
    // Заём с одной ногой приезжает обычным расходом, отличает его только ярлык
    // категории. Фильтр по kind такую операцию пропустил бы в опасную ветку
    // пуша: без плательщика она навсегда зависает в очереди, с плательщиком —
    // переписывает контрагента.
    const debt = tx("2", "проценты #налоги");
    debt.category = "Долг";
    debt.categoryFull = "Долг";
    const plan = planHashtagRename([tx("1", "#налоги"), debt], "налоги", "Налоги");
    expect(plan.rows.map((r) => r.id)).toEqual(["1"]);
    expect(plan.skipped.debts).toBe(1);
  });

  it("черновики пропускает — правки до них не доходят", () => {
    const plan = planHashtagRename(
      [tx("1", "#налоги"), tx("d1", "#налоги")],
      "налоги",
      "Налоги",
      new Set(["d1"])
    );
    expect(plan.rows.map((r) => r.id)).toEqual(["1"]);
    expect(plan.skipped.drafts).toBe(1);
  });

  it("отличает перенос от переименования", () => {
    const asRename = planHashtagRename([tx("1", "#налоги")], "налоги", "Налоги");
    expect(asRename.isMerge).toBe(false);

    // Целевой тег живёт на ДРУГОЙ операции — это уже перенос, хотя ни один
    // комментарий не схлопывается.
    const asMerge = planHashtagRename(
      [tx("1", "#налоги"), tx("2", "#бюджет")],
      "налоги",
      "бюджет"
    );
    expect(asMerge.isMerge).toBe(true);
    expect(asMerge.collapsed).toBe(0);
  });

  it("считает, сколько комментариев схлопнулось", () => {
    const plan = planHashtagRename(
      [tx("1", "аренда #налоги #бюджет"), tx("2", "#налоги")],
      "налоги",
      "бюджет"
    );
    expect(plan.collapsed).toBe(1);
    expect(plan.rows).toHaveLength(2);
  });

  it("перенос не удваивает бакет тега — главный смысл схлопывания", () => {
    const before = [tx("1", "аренда #налоги #бюджет")];
    const bucketBefore = groupByHashtag(before).find((b) => b.tag === "бюджет");
    expect(bucketBefore?.count).toBe(1);

    const plan = planHashtagRename(before, "налоги", "бюджет");
    const after = [tx("1", plan.rows[0].after)];
    const bucketAfter = groupByHashtag(after).find((b) => b.tag === "бюджет");
    // Наивная замена дала бы «#бюджет #бюджет» — count 2 и удвоенную сумму.
    expect(bucketAfter?.count).toBe(1);
    expect(bucketAfter?.expense).toBe(100);
    expect(groupByHashtag(after).find((b) => b.tag === "налоги")).toBeUndefined();
  });

  it("после переименования старого тега не остаётся ни в одном бакете", () => {
    const src = [tx("1", "#налоги"), tx("2", "оплата#налоги"), tx("3", "#налоги #еда")];
    const plan = planHashtagRename(src, "налоги", "Налоги");
    const patched = src.map((t) => {
      const row = plan.rows.find((r) => r.id === t.id);
      return row ? tx(t.id, row.after) : t;
    });
    const tags = groupByHashtag(patched).map((b) => b.tag);
    expect(tags).not.toContain("налоги");
    expect(tags).toContain("Налоги");
  });
});

describe("rulesMentioningHashtag", () => {
  it("находит правило, которое дописывает тег в комментарий", () => {
    const rules = [
      { id: "r1", name: "Зарплата", actions: [{ appendComment: "#налоги" }] },
      { id: "r2", name: "Кафе", actions: [{ setCategory: "Кафе" }] },
    ];
    expect(rulesMentioningHashtag(rules, "налоги")).toEqual(["Зарплата"]);
  });

  it("не ловится на тег, для которого наш — префикс", () => {
    const rules = [{ id: "r1", name: "Годовые", actions: [{ appendComment: "#налоги2024" }] }];
    expect(rulesMentioningHashtag(rules, "налоги")).toEqual([]);
  });

  it("различает регистр", () => {
    const rules = [{ id: "r1", name: "П", conditions: [{ value: "#Налоги" }] }];
    expect(rulesMentioningHashtag(rules, "налоги")).toEqual([]);
    expect(rulesMentioningHashtag(rules, "Налоги")).toEqual(["П"]);
  });
});

// Каждый случай ниже — подтверждённая находка состязательной проверки. Прежняя
// версия считала диапазоны удаления независимо, они пересекались у соседних
// вхождений, и правка резала живой текст.
describe("renameHashtagInComment: соседние вхождения не режут текст", () => {
  it("не съедает решётку целевого тега", () => {
    // Худший случай прошлой реализации: получалось «а бюджет» — тега нет вовсе.
    const out = rn("а #налоги #налоги#бюджет", "налоги", "бюджет");
    expect(out).toBe("а #бюджет");
    expect(extractHashtags(out)).toEqual(["бюджет"]);
  });

  it("не теряет знаки препинания после второго вхождения", () => {
    expect(rn("чек #налоги #налоги: 500 руб #бюджет", "налоги", "бюджет")).toBe(
      "чек: 500 руб #бюджет"
    );
    expect(rn("#бюджет #налоги,  #налоги. итого конец", "налоги", "бюджет")).toBe(
      "#бюджет. итого конец"
    );
  });

  it("не склеивает строки, съедая перенос", () => {
    expect(rn("#бюджет #налоги #налоги\nитого", "налоги", "бюджет")).toBe(
      "#бюджет\nитого"
    );
    expect(rn("#бюджет\nобед #налоги #налоги\nитого 500", "налоги", "бюджет")).toBe(
      "#бюджет\nобед\nитого 500"
    );
  });

  it("не съедает восклицательный знак", () => {
    expect(rn("#бюджет обед #налоги #налоги!", "налоги", "бюджет")).toBe(
      "#бюджет обед!"
    );
  });
});

describe("renameHashtagInComment: переносы строк из Windows (CRLF)", () => {
  it("уносит строку целиком так же, как при обычном переносе", () => {
    expect(rn("аренда\r\n#налоги\r\n#бюджет", "налоги", "бюджет")).toBe(
      "аренда\r\n#бюджет"
    );
    expect(rn("#бюджет\r\n#налоги\r\nитого", "налоги", "бюджет")).toBe(
      "#бюджет\r\nитого"
    );
  });

  it("даёт тот же результат, что и вариант с обычным переносом", () => {
    const crlf = rn("а\r\n#налоги\r\nб #бюджет", "налоги", "бюджет");
    const lf = rn("а\n#налоги\nб #бюджет", "налоги", "бюджет");
    expect(crlf.replace(/\r/g, "")).toBe(lf);
  });
});

describe("renameHashtagInComment: чужой текст не трогаем", () => {
  it("переименование сохраняет авторские отступы и хвостовые переносы", () => {
    // Обещание в документации функции: при переименовании не удаляется ни один
    // символ. Безусловный trim его нарушал — и правка уезжала в облако.
    expect(rn("  #налоги  ", "налоги", "Налоги")).toBe("  #Налоги  ");
    expect(rn("\nЧек №1\n#налоги\n", "налоги", "Налоги")).toBe(
      "\nЧек №1\n#Налоги\n"
    );
  });

  it("комментарий, ставший пустым после переноса, не оставляет пробелов", () => {
    // Тут удаление законно — важно лишь, чтобы не осталось строки из пробела:
    // ниже по конвейеру пустой комментарий уезжает как null.
    expect(rn("#налоги", "налоги", "бюджет")).toBe("#бюджет");
    expect(planHashtagRename([tx("1", "#бюджет #налоги")], "налоги", "бюджет")
      .rows[0].after).toBe("#бюджет");
  });
});
