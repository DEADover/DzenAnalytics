/**
 * Свободные деньги — сколько можно потратить до конца отчётного периода и
 * сколько из этого приходится на сегодня (issue #96).
 *
 * Всё здесь — чистые функции: их считает виджет на главной, но проверяются они
 * тестами без всякого экрана.
 *
 * ═══ ОТКУДА ВЗЯЛАСЬ ЭТА МОДЕЛЬ ═══════════════════════════════════════════
 *
 * Она повторяет расчёт самого Дзен-мани — не по документации, которой нет, а
 * разобранная по цифрам с живого аккаунта. Формула такая:
 *
 *     Деньги        = баланс периода + ещё поступит − не учитывать
 *     Остаток плана = Σ по строкам бюджета: (бюджет + назначенные) − факт,
 *                     каждая строка не меньше нуля
 *     Свободные     = Деньги − Остаток плана
 *
 * Сверено с экраном Дзен-мани, все совпадения точные:
 *
 *     баланс периода   99 005 = доход 160 840,26 − расход 61 835,58
 *     ещё поступит    174 600 = планы-доходы 172 600 + бюджет «Прочее» 2 000
 *     деньги          273 605 = 99 005 + 174 600
 *     остаток плана   226 391 = сумма строк списка
 *     свободные        47 213 = 273 605 − 226 391
 *     на день (ежедн.)  2 248 = 47 213 ÷ 21 день
 *     на день (накоп.)  1 086 = (47 213 − 24 408 накопленных) ÷ 21 день
 *
 * ЛИМИТ НА ДЕНЬ СЧИТАЕТСЯ ОТ СВОБОДНЫХ НА НАЧАЛО ДНЯ, а не от текущих: иначе
 * сегодняшняя трата уменьшала бы сегодняшний же лимит, и превышение никогда бы
 * не показалось. Сверено 12 сентября: свободных 40 116, за день из них ушло
 * 7 473, оставшихся дней 19 — и Дзен-мани показывает лимит 2 505 =
 * (40 116 + 7 473) ÷ 19, а сверху «4 968 ₽ сверх» = 7 473 − 2 505.
 *
 * ПОТРАЧЕНО ЗА ДЕНЬ — не сумма трат, а та их часть, которую не впитал план:
 * `траты дня − (остаток плана вчера − остаток плана сегодня)`. В тот же день
 * 15 973 ₽ трат дали 7 473 ₽ из свободных: 5 219 перебора по «Отдыху» и 2 254
 * по «Уходу за собой», остальное уместилось в бюджеты.
 *
 * Вторая сверка, 12 сентября, — она и показала, чего в модели не хватало:
 *
 *     свободные        40 116 из 51 789
 *     перебор по плану 11 673 = 5 219 + 4 200 + 2 254 по трём строкам
 *
 * «Из 51 789» — сколько свободных было бы, если бы ни одна статья не вышла за
 * свой бюджет; 40 116 — сколько осталось после перебора. Разница сходится до
 * рубля, и это доказывает, что перебор Дзен-мани считает ПО СТРОКЕ БЮДЖЕТА
 * (см. `planRemainder`), а не по ветке категорий целиком.
 *
 * ГЛАВНОЕ СЛЕДСТВИЕ, которое стоит понять до чтения кода: трата ВНУТРИ плана
 * свободные деньги не уменьшает. Она уменьшает и «Деньги», и «Остаток плана» на
 * одну и ту же сумму — разница не меняется. Свободные тратятся только тем, что
 * выходит за план: за месяц по 61 836 ₽ расходов свободные упали на 1 200 ₽.
 * Отсюда же и накопленное: лимит каждый день капает, а тратится далеко не
 * всегда.
 *
 * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ «ИТОГОВ МЕСЯЦА». Там крупное число — факт периода,
 * доход минус расход. Здесь — сколько ещё можно потратить, не залезая в
 * запланированное. Разные вопросы, разные ответы.
 */

import { DEBT_TYPES } from "./accountType";

/** Как делить свободные деньги по дням. */
export type DailyMethod = "cumulative" | "daily";

/**
 * Считать ли деньги, лежавшие на счетах к началу периода.
 *
 * Приезжает из Дзен-мани полем `user.planBalanceMode`, свои настройки для этого
 * заводить не нужно. `excludeOpeningBalance` — режим по умолчанию: в расчёт
 * идёт только то, что пришло и ушло за период. На живом аккаунте это разница
 * между 99 005 ₽ и 320 595 ₽, то есть между «сколько месяц принёс» и «сколько
 * всего лежит на картах».
 */
export type BalanceMode = "excludeOpeningBalance" | "includeOpeningBalance";

/** Счёт в том виде, в каком его знает главная. */
export interface SpendableAccount {
  title: string;
  balanceBase: number;
  type: string;
  savings: boolean;
  archive: boolean;
  offBalance: boolean;
}

/**
 * Какие счета считаются деньгами, которые можно потратить сегодня.
 *
 * Убираем четыре вида:
 *
 *   • архивные — их уже нет в обиходе;
 *   • вне баланса — человек сам сказал, что это не его повседневные деньги;
 *   • накопительные и вклады (`savings`) — деньги там есть, но тратить их
 *     сегодня не предполагается;
 *   • долговые (кредит, займ, «Долги») — там не остаток, а задолженность.
 *
 * Кредитная карта остаётся: это обычный `ccard`, и её минус — настоящие
 * потраченные деньги. Кредитный ЛИМИТ не прибавляем: занятое — не своё.
 */
export function spendableAccounts<T extends SpendableAccount>(accounts: T[]): T[] {
  return accounts.filter(
    (a) => !a.archive && !a.offBalance && !a.savings && !DEBT_TYPES.has(a.type)
  );
}

/* ─────────────────────────────  остаток плана  ───────────────────────────── */

/** Строка бюджета на месяц — то, что человек назначил категории. */
export interface PlanRow {
  /** Тег Дзен-мани. */
  tagId: string;
  title: string;
  /** Назначенная сумма расхода. */
  plan: number;
  /**
   * Замок Дзен-мани. У родителя он значит «вся категория целиком, вместе с
   * под-категориями»: тогда суммы детей — разбивка внутри неё, а не добавка.
   */
  locked: boolean;
}

/** Одна строка плана — как в списке справа у Дзен-мани. */
export interface PlanLeft {
  tagId: string;
  title: string;
  /**
   * Остаток строки. У верхней строки — вся ветка целиком, вместе с под-статьями:
   * именно так показывает Дзен-мани («Еда дома 40 909» — это 35 909 своих плюс
   * 5 000 «Алкоголя»).
   */
  left: number;
  /** Под-статьи — разбивка внутри строки. */
  children?: PlanLeft[];
}

/** Итог расчёта остатка плана. */
export interface PlanRemainder {
  /** Сумма положительных остатков — её и вычитают из денег. */
  total: number;
  /** Строки с ненулевым остатком, крупные сверху. */
  rows: PlanLeft[];
  /** Сколько потрачено сверх плана — по всем перебравшим строкам вместе. */
  overspent: number;
}

/**
 * Сколько ещё осталось потратить по плану — по каждой строке бюджета и всего.
 *
 * СЧИТАЕМ ПО СТРОКАМ БЮДЖЕТА, А НЕ ПО ВЕРХНИМ КАТЕГОРИЯМ. Каждая строка —
 * отдельный конверт: сколько в нём осталось, столько и осталось. Трата по
 * под-категории, у которой своей строки нет, попадает в БЛИЖАЙШУЮ строку вверх
 * по дереву — иначе она просто терялась бы: на живом аккаунте «София»
 * показывала 27 619 ₽ вместо 20 419, потому что 7 200 ₽ по под-тегу «Кружки»
 * не доезжали до родителя.
 *
 * ПЕРЕБОР ПО СТРОКЕ НЕ ГАСИТСЯ ОСТАТКОМ СОСЕДЕЙ. Строка, по которой потратили
 * больше плана, даёт ноль, а не минус, — и это не округление в нашу пользу, а
 * ровно то, что показывает Дзен-мани. Сверено по живым цифрам: три перебравшие
 * строки (Отдых и развлечения −5 219, Периодические −4 200, Уход за собой
 * −2 254) дают 11 673 ₽, и ровно на эти 11 673 ₽ у Дзен-мани свободные деньги
 * меньше, чем было бы без перебора: 40 116 из 51 789.
 *
 * ПОЧЕМУ ИМЕННО СТРОКА, А НЕ ВЕТКА. Перебор считается там, где стоит сумма.
 * «Периодические» с планом 3 800 ₽ перебрали на 4 200 ₽, а у их под-категории
 * «Платежи и комиссии» своя строка на 1 200 ₽ — и она цела. Считать ветку
 * целиком значило бы списать перебор родителя за счёт ребёнка: −2 900 вместо
 * −4 200, и свободных денег на 1 300 ₽ больше, чем на самом деле.
 *
 * ПОЧЕМУ НАЗНАЧЕННЫЕ ОПЕРАЦИИ ПРИБАВЛЯЮТСЯ К БЮДЖЕТУ, А НЕ ВХОДЯТ В НЕГО.
 * Так считает Дзен-мани, и это видно на живых цифрах: у «Подписок» бюджет
 * 8 719 ₽, назначенных списаний 18 101 ₽, а в остатке плана стоит 26 720 ₽.
 * Логика внятная: бюджет — сколько вы готовы потратить на категорию вообще, а
 * назначенный платёж — конкретное обязательство сверх этого.
 *
 * ЗАМОК ПОГЛОЩАЕТ ПОД-СТРОКИ. Замок у строки значит «вся ветка целиком»: суммы
 * под-категорий — разбивка внутри неё, а не добавка, поэтому их строки в расчёт
 * не идут, а траты по ним приходят в саму запертую строку. Проверено на
 * «Животных»: замок, 36 000 ₽ у родителя против 10 000 + 25 000 у детей, и на
 * экране 36 000, а не 71 000.
 *
 * ЗАМОК ЖЕ ОТМЕНЯЕТ И НАЗНАЧЕННЫЕ ОПЕРАЦИИ. Замок в Дзен-мани значит «сумму я
 * задал сам, не пересчитывай», и плановые операции к ней не прибавляются — то
 * же правило, что на странице «Бюджеты» (см. `plannedOpsByTagMonth`).
 * Проверено: «Платежи и комиссии» — 1 200 ₽ под замком и назначенный платёж на
 * 100 ₽, а на экране 1 200, а не 1 300.
 */
export function planRemainder(
  rows: PlanRow[],
  /** Назначенные операции периода, по тегу. */
  ahead: ReadonlyMap<string, number>,
  /** Потрачено с начала периода, по тегу. */
  fact: ReadonlyMap<string, number>,
  /** Тег → его родитель. Тега без записи считаем корнем. */
  parentOf: ReadonlyMap<string, string | null>
): PlanRemainder {
  const parent = (tagId: string) => parentOf.get(tagId) ?? null;
  const byTag = new Map(rows.map((r) => [r.tagId, r]));

  // Строки, у которых выше по дереву есть запертая строка, в расчёт не идут:
  // их суммы уже внутри неё. Показать их всё равно стоит — разбивкой.
  const live = new Set<string>();
  for (const r of rows) {
    let cur = parent(r.tagId);
    let swallowed = false;
    for (let i = 0; i < 32 && cur; i++) {
      if (byTag.get(cur)?.locked) {
        swallowed = true;
        break;
      }
      cur = parent(cur);
    }
    if (!swallowed) live.add(r.tagId);
  }

  /** Ближайшая строка вверх по дереву, считая сам тег. */
  const nearest = (tagId: string, within: ReadonlySet<string>): string | null => {
    let cur: string | null = tagId;
    for (let i = 0; i < 32 && cur; i++) {
      if (within.has(cur)) return cur;
      cur = parent(cur);
    }
    return null;
  };
  const gather = (
    source: ReadonlyMap<string, number>,
    within: ReadonlySet<string>
  ) => {
    const out = new Map<string, number>();
    for (const [tagId, v] of source) {
      const key = nearest(tagId, within);
      // Тег вне плана: строки у него нет и над ним тоже. Такая трата план не
      // трогает — она уходит прямо из свободных денег.
      if (key === null) continue;
      out.set(key, (out.get(key) ?? 0) + v);
    }
    return out;
  };
  const aheadBy = gather(ahead, live);
  const factBy = gather(fact, live);

  // Остаток каждой считаемой строки: перебор гасится на самой строке.
  const leftOf = new Map<string, number>();
  let overspent = 0;
  for (const tagId of live) {
    const row = byTag.get(tagId);
    if (!row) continue;
    const rest =
      row.plan +
      (row.locked ? 0 : (aheadBy.get(tagId) ?? 0)) -
      (factBy.get(tagId) ?? 0);
    leftOf.set(tagId, Math.max(0, rest));
    if (rest < 0) overspent += -rest;
  }

  // ── Разбивка по под-статьям ───────────────────────────────────────────
  // Считаемые под-строки складываются в родительскую сумму; съеденные замком
  // показываются справочно — по своему бюджету и своим тратам, как у Дзен-мани
  // («Животные 22 909» с разбивкой «Кот 8 940» и «Собака 13 778»).
  const all = new Set(byTag.keys());
  const aheadAll = gather(ahead, all);
  const factAll = gather(fact, all);

  const kids = new Map<string, string[]>();
  const tops: string[] = [];
  for (const tagId of all) {
    const up = parent(tagId);
    const holder = up === null ? null : nearest(up, all);
    if (holder === null) tops.push(tagId);
    else kids.set(holder, [...(kids.get(holder) ?? []), tagId]);
  }

  /** Сумма остатков считаемых строк ветки — то, что показывает верхняя строка. */
  const branch = (tagId: string): number => {
    const own = leftOf.get(tagId) ?? 0;
    return (kids.get(tagId) ?? []).reduce((s, k) => s + branch(k), own);
  };
  const build = (tagId: string): PlanLeft | null => {
    const row = byTag.get(tagId);
    if (!row) return null;
    const left = live.has(tagId)
      ? branch(tagId)
      : // Строка под замком родителя: в сумму ветки она уже входит, поэтому
        // показываем её собственные бюджет и траты — это разбивка, не добавка.
        Math.max(
          0,
          row.plan +
            (row.locked ? 0 : (aheadAll.get(tagId) ?? 0)) -
            (factAll.get(tagId) ?? 0)
        );
    if (left <= 0) return null;
    const children = (kids.get(tagId) ?? [])
      .map(build)
      .filter((c): c is PlanLeft => c !== null)
      .sort(byLeft);
    return children.length > 0 ? { tagId, title: row.title, left, children } : { tagId, title: row.title, left };
  };

  const out = tops
    .map(build)
    .filter((r): r is PlanLeft => r !== null)
    .sort(byLeft);
  return {
    total: [...leftOf.values()].reduce((s, v) => s + v, 0),
    rows: out,
    overspent,
  };
}

/** Крупное сверху, при равенстве — по алфавиту. */
function byLeft(a: PlanLeft, b: PlanLeft): number {
  return b.left - a.left || a.title.localeCompare(b.title, "ru");
}

/* ───────────────────────────  деньги и свободные  ─────────────────────────── */

/** Из чего сложились «Деньги до конца периода» — виджет показывает построчно. */
export interface MoneyBreakdown {
  /**
   * Баланс периода. В режиме `excludeOpeningBalance` — доход минус расход за
   * период; в `includeOpeningBalance` — остаток на повседневных счетах.
   */
  balance: number;
  /** Ещё поступит: назначенные поступления и плановый доход по бюджету. */
  stillToCome: number;
  /** Не учитывать: неснижаемый остаток из настроек. */
  excluded: number;
  /** Итог: сколько денег будет в распоряжении до конца периода. */
  total: number;
}

export function moneyBreakdown(opts: {
  balance: number;
  stillToCome: number;
  excluded: number;
}): MoneyBreakdown {
  const excluded = Math.max(0, opts.excluded);
  return {
    balance: opts.balance,
    stillToCome: opts.stillToCome,
    excluded,
    total: opts.balance + opts.stillToCome - excluded,
  };
}

/** Свободные деньги = деньги минус план на месяц. */
export function freeToSpend(money: MoneyBreakdown, planLeft: number): number {
  return money.total - planLeft;
}

/**
 * Сколько свободных денег съел сегодняшний день.
 *
 * Не сумма трат: трата внутри бюджета свободных не трогает. Считаем ту часть,
 * которую план НЕ впитал, — по тому, насколько за день просел остаток плана.
 * Сверено 12 сентября: 15 973 ₽ трат при просадке плана на 8 500 дали 7 473 ₽
 * из свободных, и ровно от этого числа Дзен-мани считает превышение дня.
 *
 * Сегодняшние поступления сюда не входят намеренно: вопрос дня — «сколько я
 * потратил», а не «как изменился баланс».
 */
export function freeSpentToday(opts: {
  /** Расход за сегодня. */
  expenseToday: number;
  /** Остаток плана на вчерашний вечер. */
  planLeftBefore: number;
  /** Остаток плана сейчас. */
  planLeftNow: number;
}): number {
  return opts.expenseToday - (opts.planLeftBefore - opts.planLeftNow);
}

/* ─────────────────────────────  дневной лимит  ───────────────────────────── */

/** Ответ на «сколько можно потратить сегодня». */
export interface DailyAllowance {
  /** Лимит на один день. */
  perDay: number;
  /**
   * Накоплено сверх дневного лимита. `null` у ежедневного метода — там копить
   * нечему, вчерашняя экономия просто чуть поднимает завтрашний лимит.
   */
  saved: number | null;
}

/**
 * Разделить свободные деньги по дням.
 *
 * ЕЖЕДНЕВНЫЙ ПЕРЕСЧЁТ: `свободные ÷ оставшиеся дни`, сегодняшний день считается
 * оставшимся. Сверено с Дзен-мани: 47 213 ÷ 21 = 2 248 ₽ — ровно то, что у него
 * на экране.
 *
 * КОПИМ СЭКОНОМЛЕННОЕ: накопленное лежит отдельной суммой, а на оставшиеся дни
 * ровно делится всё, что не накоплено: `(свободные − накоплено) ÷ оставшиеся`.
 * Сверено там же: (47 213 − 24 408) ÷ 21 = 1 086 ₽.
 *
 * Инвариант метода: `свободные = накоплено + лимит × оставшиеся дни`. Он и
 * держит расчёт честным — в последний день доступно ровно то, что осталось, ни
 * рублём больше.
 */
export function dailyAllowance(opts: {
  method: DailyMethod;
  /**
   * Свободные деньги НА НАЧАЛО ДНЯ: сегодняшние траты лимит сегодняшнего дня
   * не уменьшают, иначе превышение было бы невозможно показать.
   */
  free: number;
  /** Дней до конца периода, считая сегодняшний. */
  daysLeft: number;
  /** Накоплено с начала периода. Учитывается только накопительным методом. */
  saved: number;
}): DailyAllowance {
  const daysLeft = Math.max(1, Math.round(opts.daysLeft));
  if (opts.method === "daily") {
    return { perDay: opts.free / daysLeft, saved: null };
  }
  // Накопленное не может быть больше самих свободных: иначе лимит ушёл бы в
  // минус, обещая долг вместо денег.
  const saved = Math.min(Math.max(0, opts.saved), Math.max(0, opts.free));
  return { perDay: (opts.free - saved) / daysLeft, saved };
}

/**
 * Сколько накопилось с начала периода.
 *
 * Накопленное — это доля свободных денег, приходящаяся на уже прожитые дни:
 * `свободные × прожито ÷ всего дней`. Отсюда и лимит выходит ровно
 * `свободные ÷ всего дней` — то есть постоянный, как и обещает название метода.
 *
 * ПОЧЕМУ ТАК, А НЕ ПО ИСТОРИИ ДНЕЙ. Дзен-мани ведёт накопленное изо дня в день
 * и хранит («Сэкономлено 24 408 ₽ с 1 сентября» — это накопленный журнал, под
 * ним столбики за каждый день). Из текущего среза такое число не выводится: при
 * тех же свободных 47 213 ₽ и девяти прожитых днях ровное накопление даёт
 * 14 164 ₽, а у Дзена 24 408 — разница накопилась в дни, когда свободных денег
 * было больше. Восстановить её без ежедневного журнала нельзя, а заводить свой
 * журнал значит завязать число на то, открывали ли приложение в тот день.
 *
 * Поэтому считаем ровно: лимит один и тот же весь период, непотраченное копится.
 * Это в точности то, что написано в описании метода, — и оно проверяемо по
 * экрану, в отличие от накопленного журнала.
 *
 * Трата внутри плана накопленного не трогает: она уменьшает и деньги, и остаток
 * плана, а свободные — их разницу — оставляет на месте.
 */
export function savedSoFar(opts: {
  free: number;
  daysTotal: number;
  /** Номер сегодняшнего дня внутри периода, считая с единицы. */
  dayIndex: number;
}): number {
  const daysTotal = Math.max(1, Math.round(opts.daysTotal));
  const dayIndex = Math.min(daysTotal, Math.max(1, Math.round(opts.dayIndex)));
  // Прожито дней ДО сегодняшнего: сегодняшняя доля — это и есть лимит на сегодня.
  const lived = dayIndex - 1;
  return Math.max(0, (opts.free * lived) / daysTotal);
}

/**
 * Доля дневного лимита, которая ещё не потрачена, — для кольца.
 *
 * Считается от лимита на день, а не от накопленного: кольцо отвечает на вопрос
 * «много ли осталось на сегодня», и накопленный запас, растянувший его на
 * несколько дневных лимитов, сделал бы шкалу нечитаемой.
 */
export function allowanceRatio(today: number, perDay: number): number {
  if (!(perDay > 0)) return 0;
  return Math.max(0, Math.min(1, today / perDay));
}
