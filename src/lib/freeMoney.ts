/**
 * Свободные деньги — сколько можно потратить до конца отчётного периода и
 * сколько из этого приходится на сегодня (issue #96).
 *
 * Всё здесь — чистые функции: их считает виджет на главной, но проверяются они
 * тестами без всякого экрана.
 *
 * ═══ ОТКУДА ВЗЯЛАСЬ ЭТА МОДЕЛЬ ═══════════════════════════════════════════
 *
 * Она повторяет расчёт самого Дзен-мани — не по документации, которой нет, а
 * разобранная по цифрам с живого аккаунта. Формула такая:
 *
 *     Деньги        = баланс периода + ещё поступит − не учитывать
 *     Остаток плана = Σ по категориям: (бюджет + назначенные операции) − факт
 *     Свободные     = Деньги − Остаток плана
 *
 * Сверено с экраном Дзен-мани, все совпадения точные:
 *
 *     баланс периода   99 005 = доход 160 840,26 − расход 61 835,58
 *     ещё поступит    174 600 = планы-доходы 172 600 + бюджет «Прочее» 2 000
 *     деньги          273 605 = 99 005 + 174 600
 *     остаток плана   226 391 = сумма строк списка
 *     свободные        47 213 = 273 605 − 226 391
 *     на день (ежедн.)  2 248 = 47 213 ÷ 21 день
 *     на день (накоп.)  1 086 = (47 213 − 24 408 накопленных) ÷ 21 день
 *
 * ГЛАВНОЕ СЛЕДСТВИЕ, которое стоит понять до чтения кода: трата ВНУТРИ плана
 * свободные деньги не уменьшает. Она уменьшает и «Деньги», и «Остаток плана» на
 * одну и ту же сумму — разница не меняется. Свободные тратятся только тем, что
 * выходит за план: за месяц по 61 836 ₽ расходов свободные упали на 1 200 ₽.
 * Отсюда же и накопленное: лимит каждый день капает, а тратится далеко не
 * всегда.
 *
 * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ «ИТОГОВ МЕСЯЦА». Там крупное число — факт периода,
 * доход минус расход. Здесь — сколько ещё можно потратить, не залезая в
 * запланированное. Разные вопросы, разные ответы.
 */

import { DEBT_TYPES } from "./accountType";

/** Как делить свободные деньги по дням. */
export type DailyMethod = "cumulative" | "daily";

/**
 * Считать ли деньги, лежавшие на счетах к началу периода.
 *
 * Приезжает из Дзен-мани полем `user.planBalanceMode`, свои настройки для этого
 * заводить не нужно. `excludeOpeningBalance` — режим по умолчанию: в расчёт
 * идёт только то, что пришло и ушло за период. На живом аккаунте это разница
 * между 99 005 ₽ и 320 595 ₽, то есть между «сколько месяц принёс» и «сколько
 * всего лежит на картах».
 */
export type BalanceMode = "excludeOpeningBalance" | "includeOpeningBalance";

/** Счёт в том виде, в каком его знает главная. */
export interface SpendableAccount {
  title: string;
  balanceBase: number;
  type: string;
  savings: boolean;
  archive: boolean;
  offBalance: boolean;
}

/**
 * Какие счета считаются деньгами, которые можно потратить сегодня.
 *
 * Убираем четыре вида:
 *
 *   • архивные — их уже нет в обиходе;
 *   • вне баланса — человек сам сказал, что это не его повседневные деньги;
 *   • накопительные и вклады (`savings`) — деньги там есть, но тратить их
 *     сегодня не предполагается;
 *   • долговые (кредит, займ, «Долги») — там не остаток, а задолженность.
 *
 * Кредитная карта остаётся: это обычный `ccard`, и её минус — настоящие
 * потраченные деньги. Кредитный ЛИМИТ не прибавляем: занятое — не своё.
 */
export function spendableAccounts<T extends SpendableAccount>(accounts: T[]): T[] {
  return accounts.filter(
    (a) => !a.archive && !a.offBalance && !a.savings && !DEBT_TYPES.has(a.type)
  );
}

/* ─────────────────────────────  остаток плана  ───────────────────────────── */

/** Строка бюджета на месяц — то, что человек назначил категории. */
export interface PlanRow {
  /** Тег Дзен-мани. */
  tagId: string;
  title: string;
  /** Назначенная сумма расхода. */
  plan: number;
  /**
   * Замок Дзен-мани. У родителя он значит «вся категория целиком, вместе с
   * под-категориями»: тогда суммы детей — разбивка внутри неё, а не добавка.
   */
  locked: boolean;
}

/** Одна строка «Остатка плана» — как в списке под кольцом у Дзен-мани. */
export interface PlanLeft {
  tagId: string;
  title: string;
  left: number;
}

/**
 * Сколько ещё осталось потратить по плану — по каждой категории и всего.
 *
 * СЧИТАЕМ ПО ВЕРХНИМ КАТЕГОРИЯМ. `topOf` даёт для любого тега его верхнего
 * предка, и по нему собирается всё: план, назначенные операции, факт. Без этого
 * траты по под-категории, у которой своей строки бюджета нет, просто терялись:
 * на живом аккаунте «София» показывала 27 619 ₽ вместо 20 419 — семь тысяч
 * расходов по под-тегам не доехали до родителя.
 *
 * ПОЧЕМУ НАЗНАЧЕННЫЕ ОПЕРАЦИИ ПРИБАВЛЯЮТСЯ К БЮДЖЕТУ, А НЕ ВХОДЯТ В НЕГО.
 * Так считает Дзен-мани, и это видно на живых цифрах: у «Подписок» бюджет
 * 8 719 ₽, назначенных списаний на 18 101 ₽, а в остатке плана стоит 26 720 ₽.
 * Логика внятная: бюджет — сколько вы готовы потратить на категорию вообще, а
 * назначенный платёж — конкретное обязательство сверх этого.
 *
 * ЗАМОК У РОДИТЕЛЯ МЕНЯЕТ АРИФМЕТИКУ. Без замка план категории = свой плюс все
 * под-категории. С замком родительская сумма и есть весь бюджет ветки, а дети
 * лишь показывают, как он разложен. Проверено на «Животных»: замок, 36 000 ₽ у
 * родителя против 10 000 + 25 000 у детей, и на экране 36 000, а не 71 000.
 *
 * Категория, по которой потратили больше плана, даёт ноль, а не минус: перебор
 * по одной статье не развязывает руки по остальным.
 */
export function planRemainder(
  rows: PlanRow[],
  /** Назначенные операции впереди, по тегу. */
  ahead: ReadonlyMap<string, number>,
  /** Потрачено с начала периода, по тегу. */
  fact: ReadonlyMap<string, number>,
  /** Тег → его верхняя категория. Тег без записи считается своим же корнем. */
  topOf: ReadonlyMap<string, string>
): { total: number; rows: PlanLeft[] } {
  const top = (tagId: string) => topOf.get(tagId) ?? tagId;

  const lockedTop = new Set<string>();
  for (const r of rows) if (r.locked && top(r.tagId) === r.tagId) lockedTop.add(r.tagId);

  const plan = new Map<string, number>();
  const title = new Map<string, string>();
  for (const r of rows) {
    const t = top(r.tagId);
    if (!title.has(t) || r.tagId === t) title.set(t, r.tagId === t ? r.title : title.get(t) ?? r.title);
    // Замок у родителя: план ветки — это его сумма, детей не прибавляем.
    if (lockedTop.has(t) && r.tagId !== t) continue;
    plan.set(t, (plan.get(t) ?? 0) + r.plan);
  }

  const sum = (m: ReadonlyMap<string, number>) => {
    const out = new Map<string, number>();
    for (const [tagId, v] of m) {
      const t = top(tagId);
      out.set(t, (out.get(t) ?? 0) + v);
    }
    return out;
  };
  const aheadTop = sum(ahead);
  const factTop = sum(fact);

  const out: PlanLeft[] = [];
  for (const t of new Set([...plan.keys(), ...aheadTop.keys()])) {
    const left = Math.max(
      0,
      (plan.get(t) ?? 0) + (aheadTop.get(t) ?? 0) - (factTop.get(t) ?? 0)
    );
    if (left > 0) out.push({ tagId: t, title: title.get(t) ?? t, left });
  }
  out.sort((a, b) => b.left - a.left || a.title.localeCompare(b.title, "ru"));
  return { total: out.reduce((s, r) => s + r.left, 0), rows: out };
}

/* ───────────────────────────  деньги и свободные  ─────────────────────────── */

/** Из чего сложились «Деньги до конца периода» — виджет показывает построчно. */
export interface MoneyBreakdown {
  /**
   * Баланс периода. В режиме `excludeOpeningBalance` — доход минус расход за
   * период; в `includeOpeningBalance` — остаток на повседневных счетах.
   */
  balance: number;
  /** Ещё поступит: назначенные поступления и плановый доход по бюджету. */
  stillToCome: number;
  /** Не учитывать: неснижаемый остаток из настроек. */
  excluded: number;
  /** Итог: сколько денег будет в распоряжении до конца периода. */
  total: number;
}

export function moneyBreakdown(opts: {
  balance: number;
  stillToCome: number;
  excluded: number;
}): MoneyBreakdown {
  const excluded = Math.max(0, opts.excluded);
  return {
    balance: opts.balance,
    stillToCome: opts.stillToCome,
    excluded,
    total: opts.balance + opts.stillToCome - excluded,
  };
}

/** Свободные деньги = деньги минус остаток плана. */
export function freeToSpend(money: MoneyBreakdown, planLeft: number): number {
  return money.total - planLeft;
}

/* ─────────────────────────────  дневной лимит  ───────────────────────────── */

/** Ответ на «сколько можно потратить сегодня». */
export interface DailyAllowance {
  /** Лимит на один день. */
  perDay: number;
  /**
   * Накоплено сверх дневного лимита. `null` у ежедневного метода — там копить
   * нечему, вчерашняя экономия просто чуть поднимает завтрашний лимит.
   */
  saved: number | null;
}

/**
 * Разделить свободные деньги по дням.
 *
 * ЕЖЕДНЕВНЫЙ ПЕРЕСЧЁТ: `свободные ÷ оставшиеся дни`, сегодняшний день считается
 * оставшимся. Сверено с Дзен-мани: 47 213 ÷ 21 = 2 248 ₽ — ровно то, что у него
 * на экране.
 *
 * КОПИМ СЭКОНОМЛЕННОЕ: накопленное лежит отдельной суммой, а на оставшиеся дни
 * ровно делится всё, что не накоплено: `(свободные − накоплено) ÷ оставшиеся`.
 * Сверено там же: (47 213 − 24 408) ÷ 21 = 1 086 ₽.
 *
 * Инвариант метода: `свободные = накоплено + лимит × оставшиеся дни`. Он и
 * держит расчёт честным — в последний день доступно ровно то, что осталось, ни
 * рублём больше.
 */
export function dailyAllowance(opts: {
  method: DailyMethod;
  free: number;
  /** Дней до конца периода, считая сегодняшний. */
  daysLeft: number;
  /** Накоплено с начала периода. Учитывается только накопительным методом. */
  saved: number;
}): DailyAllowance {
  const daysLeft = Math.max(1, Math.round(opts.daysLeft));
  if (opts.method === "daily") {
    return { perDay: opts.free / daysLeft, saved: null };
  }
  // Накопленное не может быть больше самих свободных: иначе лимит ушёл бы в
  // минус, обещая долг вместо денег.
  const saved = Math.min(Math.max(0, opts.saved), Math.max(0, opts.free));
  return { perDay: (opts.free - saved) / daysLeft, saved };
}

/**
 * Сколько накопилось с начала периода.
 *
 * Накопленное — это доля свободных денег, приходящаяся на уже прожитые дни:
 * `свободные × прожито ÷ всего дней`. Отсюда и лимит выходит ровно
 * `свободные ÷ всего дней` — то есть постоянный, как и обещает название метода.
 *
 * ПОЧЕМУ ТАК, А НЕ ПО ИСТОРИИ ДНЕЙ. Дзен-мани ведёт накопленное изо дня в день
 * и хранит («Сэкономлено 24 408 ₽ с 1 сентября» — это накопленный журнал, под
 * ним столбики за каждый день). Из текущего среза такое число не выводится: при
 * тех же свободных 47 213 ₽ и девяти прожитых днях ровное накопление даёт
 * 14 164 ₽, а у Дзена 24 408 — разница накопилась в дни, когда свободных денег
 * было больше. Восстановить её без ежедневного журнала нельзя, а заводить свой
 * журнал значит завязать число на то, открывали ли приложение в тот день.
 *
 * Поэтому считаем ровно: лимит один и тот же весь период, непотраченное копится.
 * Это в точности то, что написано в описании метода, — и оно проверяемо по
 * экрану, в отличие от накопленного журнала.
 *
 * Трата внутри плана накопленного не трогает: она уменьшает и деньги, и остаток
 * плана, а свободные — их разницу — оставляет на месте.
 */
export function savedSoFar(opts: {
  free: number;
  daysTotal: number;
  /** Номер сегодняшнего дня внутри периода, считая с единицы. */
  dayIndex: number;
}): number {
  const daysTotal = Math.max(1, Math.round(opts.daysTotal));
  const dayIndex = Math.min(daysTotal, Math.max(1, Math.round(opts.dayIndex)));
  // Прожито дней ДО сегодняшнего: сегодняшняя доля — это и есть лимит на сегодня.
  const lived = dayIndex - 1;
  return Math.max(0, (opts.free * lived) / daysTotal);
}

/**
 * Доля дневного лимита, которая ещё не потрачена, — для кольца.
 *
 * Считается от лимита на день, а не от накопленного: кольцо отвечает на вопрос
 * «много ли осталось на сегодня», и накопленный запас, растянувший его на
 * несколько дневных лимитов, сделал бы шкалу нечитаемой.
 */
export function allowanceRatio(today: number, perDay: number): number {
  if (!(perDay > 0)) return 0;
  return Math.max(0, Math.min(1, today / perDay));
}
