/**
 * Свободные деньги — сколько можно потратить до конца отчётного периода и
 * сколько из этого приходится на сегодня (issue #96).
 *
 * Всё здесь — чистые функции: их считает виджет на главной, но проверяются они
 * тестами без всякого экрана.
 *
 * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ «ИТОГОВ МЕСЯЦА». Там крупное число — это факт периода,
 * доход минус расход, и ничего кроме. Здесь — деньги, которые лежат на счетах
 * прямо сейчас, за вычетом того, что до конца периода уже обещано планам. Два
 * разных вопроса: «сколько месяц принёс» и «сколько ещё можно потратить».
 */

import { DEBT_TYPES } from "./accountType";

/** Как делить свободные деньги по дням. */
export type DailyMethod = "cumulative" | "daily";

export const DAILY_METHODS: { id: DailyMethod; title: string; hint: string }[] = [
  {
    id: "cumulative",
    title: "Накопительный",
    hint: "Лимит на день постоянный, а непотраченное переносится на следующий день",
  },
  {
    id: "daily",
    title: "Ежедневный",
    hint: "Лимит пересчитывается каждый день заново по остатку и оставшимся дням",
  },
];

/** Счёт в том виде, в каком его знает главная. */
export interface SpendableAccount {
  title: string;
  balanceBase: number;
  type: string;
  savings: boolean;
  archive: boolean;
  offBalance: boolean;
}

/**
 * Какие счета считаются деньгами, которые можно потратить сегодня.
 *
 * Убираем четыре вида:
 *
 *   • архивные — их уже нет в обиходе;
 *   • вне баланса — человек сам сказал, что это не его повседневные деньги;
 *   • накопительные и вклады (`savings`) — деньги там есть, но тратить их
 *     сегодня не предполагается, а с ними «свободные» вырастают в разы и
 *     перестают отвечать на свой вопрос;
 *   • долговые (кредит, займ, «Долги») — там не остаток, а задолженность.
 *
 * Кредитная карта при этом остаётся: это обычный `ccard`, и её минус —
 * настоящие потраченные деньги, которые надо вернуть. Кредитный ЛИМИТ к
 * свободным деньгам не прибавляем: занятое — не своё.
 */
export function spendableAccounts<T extends SpendableAccount>(accounts: T[]): T[] {
  return accounts.filter(
    (a) => !a.archive && !a.offBalance && !a.savings && !DEBT_TYPES.has(a.type)
  );
}

/** Плановая операция в том виде, в каком её знает расчёт. */
export interface PlannedLeg {
  date: string;
  kind: "expense" | "income" | "transfer";
  amountBase: number;
  /** Счёт, с которого спишется (расход) или на который придёт (доход). */
  account: string;
  /** Прогноз Дзен-мани, а не заведённый человеком план. */
  forecast: boolean;
}

/** Плановые доходы и расходы до конца периода — по учитываемым счетам. */
export interface PlannedSums {
  income: number;
  expense: number;
  /** Сколько из расходов уже просрочено: стоит в прошлом, но не проведено. */
  overdueExpense: number;
}

/**
 * Сложить планы, которые повлияют на деньги до конца периода.
 *
 * ПРОГНОЗЫ НЕ БЕРЁМ. Прогноз — догадка Дзен-мани по регулярности, а не
 * обещание. Вычитать догадку из живых денег значит без причины занижать лимит:
 * человек увидит меньше, чем у него есть, и не поймёт, откуда взялась разница.
 *
 * ПРОСРОЧЕННОЕ БЕРЁМ. Дата прошла, а платёж не проведён — деньги всё ещё нужны,
 * и делать вид, что обязательство исчезло вместе с датой, нельзя.
 *
 * ПЕРЕВОДЫ НЕ БЕРЁМ: перекладывание между своими счетами денег не тратит.
 *
 * Планы на счетах, которых нет среди учитываемых (накопительный, кредит),
 * пропускаем: их остатки в сумме не участвуют, значит и списания с них ничего
 * в ней не меняют.
 */
export function plannedSums(
  legs: PlannedLeg[],
  periodEnd: string,
  today: string,
  accounts: Set<string>
): PlannedSums {
  let income = 0;
  let expense = 0;
  let overdueExpense = 0;
  for (const p of legs) {
    if (p.forecast) continue;
    if (p.kind === "transfer") continue;
    if (p.date > periodEnd) continue;
    if (!accounts.has(p.account)) continue;
    if (p.kind === "income") {
      income += p.amountBase;
    } else {
      expense += p.amountBase;
      if (p.date < today) overdueExpense += p.amountBase;
    }
  }
  return { income, expense, overdueExpense };
}

/** Из чего сложились свободные деньги — виджет показывает это построчно. */
export interface FreeBreakdown {
  /** Деньги на учитываемых счетах. */
  onAccounts: number;
  /** Плановые поступления до конца периода. */
  plannedIncome: number;
  /** Плановые списания до конца периода. */
  plannedExpense: number;
  /** Неснижаемый остаток, заданный в настройках. */
  reserve: number;
  /** Итог: сколько можно потратить до конца периода. */
  free: number;
}

/**
 * Свободные деньги на остаток периода.
 *
 * Плановые ДОХОДЫ прибавляем — так же, как это делает Дзен-мани. Побочный
 * эффект честный, но резкий: за день до зарплаты сумма подскакивает на всю
 * зарплату. Поэтому виджет показывает слагаемые отдельной строкой — скачок
 * должен быть объясним, а не выглядеть ошибкой счёта.
 */
export function freeBreakdown(opts: {
  onAccounts: number;
  planned: PlannedSums;
  reserve: number;
}): FreeBreakdown {
  const { onAccounts, planned } = opts;
  const reserve = Math.max(0, opts.reserve);
  return {
    onAccounts,
    plannedIncome: planned.income,
    plannedExpense: planned.expense,
    reserve,
    free: onAccounts + planned.income - planned.expense - reserve,
  };
}

/** Ответ на «сколько можно потратить сегодня». */
export interface DailyAllowance {
  /** Лимит на один день. */
  perDay: number;
  /** Сколько доступно именно сегодня. У ежедневного метода равен `perDay`. */
  today: number;
  /**
   * Накоплено сверх дневного лимита (или перерасходовано, если отрицательное).
   * `null` у ежедневного метода — там копить нечему.
   */
  carried: number | null;
}

/**
 * Разделить свободные деньги по дням.
 *
 * ЕЖЕДНЕВНЫЙ метод: `свободные ÷ оставшиеся дни`. Сегодняшний день считается
 * оставшимся — он ещё не прожит. Сэкономленное вчера растворяется в остатке и
 * чуть поднимает лимит, но отдельно его не видно.
 *
 * НАКОПИТЕЛЬНЫЙ: лимит на день один на весь период, а несделанные траты
 * переносятся. Бюджет периода восстанавливаем как «свободные сейчас плюс уже
 * потраченное» — это ровно те деньги, которые были в распоряжении с начала
 * периода. Дальше `лимит × прожитые дни − потрачено`: не потратив ничего три
 * дня, на четвёртый можно потратить вчетверо больше.
 *
 * Лимит здесь «постоянный» с оговоркой: пришедшая среди периода зарплата
 * поднимает бюджет, а с ним и лимит. Иначе нельзя — будущий доход нам
 * неизвестен, а делать вид, что денег по-прежнему нет, значило бы занижать
 * лимит до самого конца периода.
 *
 * ПОЧЕМУ «ПОТРАЧЕНО» — ЭТО ВСЕ РАСХОДЫ, включая проведённые по планам. Двойного
 * счёта тут нет: проведённый план уже ушёл из списка будущих и уменьшил остаток
 * на счёте, а в бюджет периода он возвращается именно через «потрачено».
 */
export function dailyAllowance(opts: {
  method: DailyMethod;
  free: number;
  /** Длина периода в днях. */
  daysTotal: number;
  /** Номер сегодняшнего дня внутри периода, считая с единицы. */
  dayIndex: number;
  /** Потрачено с начала периода по учитываемым счетам. */
  spent: number;
}): DailyAllowance {
  const daysTotal = Math.max(1, Math.round(opts.daysTotal));
  const dayIndex = Math.min(daysTotal, Math.max(1, Math.round(opts.dayIndex)));
  const daysLeft = daysTotal - dayIndex + 1;

  if (opts.method === "daily") {
    const perDay = opts.free / daysLeft;
    return { perDay, today: perDay, carried: null };
  }

  const budget = opts.free + opts.spent;
  const perDay = budget / daysTotal;
  const today = perDay * dayIndex - opts.spent;
  return { perDay, today, carried: today - perDay };
}

/**
 * Доля сегодняшнего лимита, которая ещё не потрачена, — для кольца.
 *
 * Считается от лимита на день, а не от накопленного: кольцо отвечает на вопрос
 * «много ли осталось на сегодня», и накопленный запас, растянувший его на
 * несколько дневных лимитов, сделал бы шкалу нечитаемой. Поэтому доля
 * подрезана единицей сверху и нулём снизу.
 */
export function allowanceRatio(a: DailyAllowance): number {
  if (!(a.perDay > 0)) return 0;
  return Math.max(0, Math.min(1, a.today / a.perDay));
}
