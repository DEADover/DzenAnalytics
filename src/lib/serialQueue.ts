/**
 * Очередь действий хранилища: следующее начинается, когда закончилось
 * предыдущее.
 *
 * Действия хранилищ очереди отправки устроены «прочитал → записал на диск →
 * положил в память». Два пересекающихся вызова в одной вкладке (две правки
 * подряд, правка во время чистки после отправки) читали одно и то же
 * состояние, и второй молча затирал результат первого. В очереди каждый
 * видит то, что оставил предыдущий.
 *
 * Действие в очереди не должно ждать другое действие того же хранилища —
 * встанет навсегда. Делегирующие («одно — это много из одного») в очередь не
 * ставятся: в ней окажется то, к чему они обращаются.
 */
export function serialQueue(): <T>(fn: () => Promise<T>) => Promise<T> {
  let tail: Promise<unknown> = Promise.resolve();
  return <T>(fn: () => Promise<T>): Promise<T> => {
    const run = tail.then(fn);
    // Упавшее действие очередь не останавливает.
    tail = run.catch(() => {});
    return run;
  };
}
