/**
 * Придержать автоматическую отправку правок в Дзен-мани.
 *
 * Пока висит плашка с «Отменить», правка ещё может передумать: удаление
 * вернуться, сумма откатиться. Режим «Авто» отправляет через две секунды после
 * последней правки — раньше, чем человек дочитает плашку, — и «Отменить» после
 * этого означало бы вторую отправку поверх первой (а удалённую в облаке
 * операцию вернуть можно только копией). Поэтому отправка ждёт, пока плашка не
 * уйдёт, и уходит уже то, на чём человек остановился.
 *
 * Держится только автоматическая отправка: ручную и «при синхронизации»
 * человек запускает сам.
 */
let heldUntil = 0;

/**
 * Самое долгое ожидание. Плашка с отменой держит отправку, пока видна, а
 * видна она дольше обычного, пока на ней мышь, — но не бесконечно: если
 * плашку почему-то никто не снял, правки всё равно уйдут.
 */
export const MAX_HOLD_MS = 60_000;

/** Не отправлять ещё `ms` миллисекунд (продлевает, но не укорачивает). */
export function holdPush(ms: number = MAX_HOLD_MS): void {
  heldUntil = Math.max(heldUntil, Date.now() + ms);
}

/** Отпустить сразу — плашку закрыли или отменили. */
export function releasePush(): void {
  heldUntil = 0;
}

/** Сколько ещё ждать, мс; 0 — можно отправлять. */
export function pushHoldLeft(): number {
  return Math.max(0, heldUntil - Date.now());
}
