/**
 * Деньги в базовой валюте — до копейки.
 *
 * Сумма в чужой валюте, умноженная на курс, выходит с хвостом: 606,4932 $ по
 * 82,2281 — это 49 870,7834… ₽. Каждую строку экран округляет до копейки сам,
 * а итог складывался из неокруглённых значений, и сумма строк расходилась с
 * итогом на копейку-две. В Дзен-мани пересчитанная сумма — уже копейки, так
 * что округляем там же, где пересчитываем, а дальше всё складывается ровно.
 */
export function roundMoney(value: number): number {
  if (!Number.isFinite(value)) return value;
  // Сдвиг на EPSILON — чтобы 1,005 стало 1,01, а не 1,00 из-за двоичной записи.
  const r = Math.round((Math.abs(value) + Number.EPSILON) * 100) / 100;
  return value < 0 ? -r : r;
}

/** Сумма денежных значений до копейки: без хвостов вроде 0,1 + 0,2 = 0,30000000000000004. */
export function sumMoney(values: Iterable<number>): number {
  let s = 0;
  for (const v of values) s += v;
  return roundMoney(s);
}
