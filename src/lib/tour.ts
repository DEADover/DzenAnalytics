/**
 * Обучение по живому интерфейсу: главы и их шаги.
 *
 * Шаг подсвечивает настоящий элемент панели — его помечает атрибут
 * `data-tour="…"`; `метка:first` — первый элемент внутри неё. Если элемента нет (узкое окно, нет
 * подключения, фильтр спрятан в шапку), берётся следующий из списка `target`,
 * а если нет ни одного — карточка встаёт по центру и объясняет словами.
 *
 * Текст — абзацы; `**так**` выделяется полужирным.
 */
