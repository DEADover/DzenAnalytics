export function tourChapter(id: string): TourChapter | undefined {
  return TOUR_CHAPTERS.find((c) => c.id === id);
}

/** «≈2 мин» — по 12 секунд на шаг, не меньше минуты. */
export function chapterDuration(c: TourChapter): string {
  return `≈${Math.max(1, Math.round((c.steps.length * 12) / 60))} мин`;
}
