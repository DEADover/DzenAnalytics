/**
 * Обучение по живому интерфейсу: главы и их шаги.
 *
 * Шаг подсвечивает настоящий элемент панели — его помечает атрибут
 * `data-tour="…"`; `метка:first` — первый элемент внутри неё. Если элемента
 * нет (узкое окно, нет подключения, один аккаунт), берётся следующий из списка
 * `target`, а если нет ни одного — карточка встаёт по центру и объясняет словами.
 *
 * Текст — абзацы; `**так**` выделяется полужирным. Подписи кнопок и пунктов —
 * дословно как в интерфейсе: обучение, которое называет кнопку иначе, чем она
 * подписана, только путает. Меняете подпись в панели — поменяйте и здесь.
 */
import type { LucideIcon } from "lucide-react";
import { LayoutDashboard, PlugZap, Sparkles } from "lucide-react";

/** Событие, которым тур раскрывает и закрывает панель «Ещё» (слушает `TopNav`). */
export const TOUR_MORE_EVENT = "dzen:tour-more";

/** Что шаг раскрывает на время показа: панель «Ещё» или окно настройки меню. */
export type TourOpen = "more" | "nav-editor";

export interface TourStep {
  /** Куда перейти перед шагом. Путь с параметрами: `/settings?tab=interface`. */
  route?: string;
  /** Метки `data-tour` по порядку предпочтения; нет — карточка по центру. */
  target?: string[];
  title: string;
  body: string[];
  /** Особый вид шага: приветствие или финал главы. */
  kind?: "welcome" | "finish";
  /** Раскрыть на время шага; закроется само, когда тур уйдёт дальше. */
  open?: TourOpen;
}

export interface TourChapter {
  id: string;
  title: string;
  /** Одна строка в центре обучения. */
  summary: string;
  /** О чём глава — метками в центре обучения. */
  topics: string[];
  icon: LucideIcon;
  steps: TourStep[];
}

