/**
 * Режим правила — одно свойство с тремя состояниями вместо двух флажков.
 *
 * В хранилище режим лежит двумя полями: `enabled` («работает вообще») и
 * `autoApply` («работает само»). Независимыми переключателями они выглядели как
 * две настройки, хотя автоприменение у выключенного правила не значит ничего.
 * Здесь перевод в обе стороны и обратно — чтобы таблица, карточка правила и
 * хранилище понимали режим одинаково.
 */

import type { PushMode } from "../store/useZenmoneyStore";

export type RuleMode = "off" | "manual" | "auto";

/** Режим правила по его полям хранилища. */
export function ruleModeOf(rule: { enabled: boolean; autoApply?: boolean }): RuleMode {
  if (!rule.enabled) return "off";
  return rule.autoApply ? "auto" : "manual";
}

/**
 * Поля хранилища по режиму — обратная сторона `ruleModeOf`.
 *
 * Оба поля задаются ЯВНО: иначе у выключенного правила осталось бы висеть
 * `autoApply: true`, невидимое на экране и оживающее при включении.
 */
export function ruleModeFields(mode: RuleMode): { enabled: boolean; autoApply: boolean } {
  return { enabled: mode !== "off", autoApply: mode === "auto" };
}

/**
 * Что случится с тем, что правило запишет, — по текущему режиму отправки.
 *
 * Правило само в облако не пишет никогда: оно кладёт правку в тот же слой, что
 * и рука, а дальше решает отправка. Человек, включающий «Авто», спрашивает про
 * облако в ту же секунду — и ответ должен стоять там же, где переключатель, а
 * не в другом разделе настроек.
 */
export function pushNote(mode: PushMode): { text: string; tone?: "warn" } {
  if (mode === "auto") {
    return {
      text: "Уедет в Дзен-мани само — отправка на «Авто».",
      tone: "warn",
    };
  }
  if (mode === "manual") {
    return { text: "Уедет по кнопке «Отправить» в шапке." };
  }
  if (mode === "on-sync") {
    return { text: "Уедет со следующей синхронизацией." };
  }
  return { text: "Останется на устройстве: отправка выключена." };
}
