// Переименование и перенос хэштегов, живущих внутри комментариев к операциям.
//
// В Дзен-мани у хэштега нет собственной сущности: «#налоги» — это просто текст
// в поле comment. Значит и переименование — не правка справочника, а массовая
// переписка комментариев. Отсюда все требования ниже.
//
// ВАЖНО про терминологию: в коде проекта `tag` — это КАТЕГОРИЯ Дзен-мани
// (сущность tag в его API), а хэштег из комментария всегда зовётся `hashtag`.
// Здесь — только хэштеги.

import { HASHTAG_RE, extractHashtags } from "./aggregations";
import type { Transaction } from "../types";

/**
 * Переписать один комментарий: заменить хэштег `from` на `to`.
 *
 * Две ветки, и разница между ними принципиальная:
 *
 * - **Переименование** (целевого тега в этом комментарии нет) — меняем КАЖДОЕ
 *   вхождение и больше ничего не трогаем. Ни один символ не удаляется.
 * - **Перенос** (целевой тег в комментарии уже есть) — убираем переименованные
 *   вхождения, оставляя существующий целевой тег на месте.
 *
 * Соблазн «всегда схлопывать повторы» надо гасить: в комментарии
 * «оплата#налоги и ссылка /#налоги» второе вхождение — якорь ссылки, а не
 * дубль тега, и удалять его при простом переименовании нельзя. Удаляем текст
 * только там, где перенос иначе СОЗДАЛ БЫ дубль.
 *
 * Остальные требования:
 *
 * 1. Совпадение только ПОЛНОЕ. `replaceAll("#налог", "#сборы")` на строке
 *    «#налог и #налоги» портит второй тег в «#сборыи». Поэтому идём по той же
 *    регулярке, что и разбор, и сравниваем захваченную группу целиком.
 * 2. Регистр значим. «#налоги» и «#Налоги» — РАЗНЫЕ теги (ключи Map сравниваются
 *    побайтово), поэтому сравнение строгое и никаких `toLowerCase`. Тем более
 *    никакого `toLocaleLowerCase`: в турецкой локали он разводит I и i, а
 *    «İ».toLowerCase() вообще даёт два кодпоинта и ломает смещения.
 * 3. Дубль недопустим. Перенос «#налоги» в «#бюджет» на комментарии
 *    «аренда #налоги #бюджет» наивно даёт «#бюджет #бюджет» — а это удвоенная
 *    сумма и удвоенный счётчик операций в бакете, потому что groupByHashtag
 *    считает КАЖДОЕ вхождение.
 * 4. После удаления лишнего токена остаётся мусор: двойной пробел, висящая
 *    запятая, пустая строка. Их убираем прицельно, а не глобальной чисткой,
 *    чтобы не тронуть авторские переносы строк.
 */
export function renameHashtagInComment(
  comment: string,
  from: string,
  to: string
): string {
  if (!comment || !from || !to || from === to) return comment;

  const matches = [...comment.matchAll(HASHTAG_RE)];
  // Ни одного вхождения переименовываемого тега — комментарий не наш.
  // Проверка именно на `from`: комментарий, где есть только целевой тег,
  // трогать нельзя, иначе перенос «схлопнет» чужие дубли ни за что.
  if (!matches.some((m) => m[1] === from)) return comment;

  // Есть ли целевой тег в этом же комментарии — тогда это перенос, и
  // переименованные вхождения не заменяются, а удаляются.
  const isMerge = matches.some((m) => m[1] === to);

  // Собираем результат ОДНИМ проходом слева направо, с курсором по исходной
  // строке. Так устроено намеренно: предыдущая версия считала диапазоны
  // удаления независимо друг от друга, и у двух соседних вхождений они
  // пересекались — первое съедало разделитель вперёд, второе тот же самый
  // разделитель назад. При применении справа налево смещения разъезжались и
  // резали живой текст: «а #налоги #налоги#бюджет» превращалось в «а бюджет»,
  // то есть операция теряла тег вообще. Здесь курсор физически не даёт
  // откусить левее уже выведенного.
  let out = "";
  let cursor = 0;
  for (const m of matches) {
    if (m[1] !== from) continue;
    const start = m.index ?? 0;
    const end = start + m[0].length;
    out += comment.slice(cursor, start);
    cursor = end;
    if (!isMerge) {
      out += `#${to}`;
      continue;
    }
    const seam = tidySeam(out, comment, end);
    out = seam.out;
    cursor = seam.cursor;
  }
  out += comment.slice(cursor);
  // Единственная вольность с текстом за пределами тега: комментарий, от
  // которого остались одни пробелы, схлопываем в пустой. Общего trim нет
  // намеренно — при переименовании мы обещали не трогать ни одного символа,
  // включая авторские отступы и хвостовые переносы.
  return /^\s*$/.test(out) ? "" : out;
}

/** Горизонтальный пробел с необязательным разделителем — то, что прилипает к тегу. */
const GLUE_AFTER = /^[^\S\r\n]*[,;]?[^\S\r\n]*/;
const GLUE_BEFORE = /[^\S\r\n]*[,;]?[^\S\r\n]*$/;
/** Пусто ли то, что осталось от строки. `\r` сюда входит — см. CRLF ниже. */
const BLANK_LINE_PART = /^\s*[,;]?\s*$/;
/** Знаки, перед которыми пробел не ставят. Открывающая скобка сюда не входит. */
const CLOSING_PUNCT = /[.,;:!?)»"'…]/;
/** Хвост последней строки уже собранного текста. */
const LAST_LINE = /(?:^|\n)([^\n]*)$/;

/**
 * Подчистить шов, оставшийся от удалённого тега.
 *
 * Решение принимается по уже выведенному тексту слева и по остатку строки
 * справа, поэтому «съесть» чужой разделитель невозможно.
 *
 * - Тег стоял на строке один — уносим строку целиком вместе с переносом.
 * - Справа конец строки или знак вроде точки и запятой — убираем пробел слева,
 *   иначе получится «чек : 500».
 * - Иначе съедаем прилипший разделитель справа, а если его нет — не трогаем
 *   ничего: соседние слова и так сомкнутся через уже имеющийся пробел.
 */
function tidySeam(
  out: string,
  comment: string,
  end: number
): { out: string; cursor: number } {
  const nl = comment.indexOf("\n", end);
  const lineEnd = nl === -1 ? comment.length : nl;
  // Остаток строки справа. При CRLF он начинается с `\r` — поэтому проверка на
  // пустоту берёт весь `\s`, а не только горизонтальный пробел: иначе перенос
  // из Windows-приложения не опознавался и на месте тега оставалась пустая
  // строка.
  const rest = comment.slice(end, lineEnd);
  const lineTail = LAST_LINE.exec(out)?.[1] ?? "";

  if (BLANK_LINE_PART.test(lineTail) && BLANK_LINE_PART.test(rest)) {
    const withoutLine = out.replace(/\r?\n[^\S\r\n]*$/, "");
    // Строка была не первой — унесли её вместе с переносом слева.
    if (withoutLine !== out) return { out: withoutLine, cursor: end };
    // Тег стоял на первой строке — тогда съедаем перенос справа.
    return { out, cursor: nl === -1 ? comment.length : nl + 1 };
  }

  const fwd = GLUE_AFTER.exec(rest)?.[0] ?? "";
  const nextCh = rest.slice(fwd.length).charAt(0);
  if (nextCh === "" || CLOSING_PUNCT.test(nextCh)) {
    return { out: out.replace(GLUE_BEFORE, ""), cursor: end + fwd.length };
  }
  return { out, cursor: end + fwd.length };
}

export interface HashtagRenameRow {
  id: string;
  date: string;
  payee: string;
  amountBase: number;
  kind: Transaction["kind"];
  before: string;
  after: string;
}

export interface HashtagRenamePlan {
  /** Операции, комментарий которых реально изменится. */
  rows: HashtagRenameRow[];
  /**
   * Операции, которые мы намеренно не трогаем, с причинами.
   *
   * Это БЕЛЫЙ список наоборот: переписываем только те виды операций, про
   * которые точно известно, что правка одного комментария уедет в Дзен-мани
   * без побочного урона. Всё остальное считаем опасным по умолчанию.
   */
  skipped: {
    /**
     * Долговые операции — те, что идут по счёту типа loan / credit / debt.
     * Опасный класс там определяется ТИПОМ СЧЁТА, а не видом операции: заём
     * с одной ногой приезжает как обычный расход и по `kind` не отличается.
     * Признак — ярлык категории «Долг», который ставит прямой маппер. Такая
     * правка уходит в ветку D пуша: без заполненного плательщика она вечно
     * висит в очереди, а с заполненным — переписывает контрагента.
     */
    debts: number;
    /**
     * Черновики — созданные локально и ещё не отправленные операции. Правки
     * до них не доходят: конвейер дописывает черновики ПОСЛЕ наложения правок
     * (`useDataStore.finalize`), так что запись была бы молчаливо пустой.
     */
    drafts: number;
  };
  /** Это перенос в уже существующий тег, а не переименование. */
  isMerge: boolean;
  /** В скольких комментариях оба тега встретились вместе и схлопнулись в один. */
  collapsed: number;
}

/** Ярлык, которым прямой маппер помечает операции по долговым счетам. */
const DEBT_LABEL = "Долг";

/**
 * Можно ли безопасно переписать комментарий этой операции.
 *
 * Именно белый список: неизвестный вид операции считается опасным, а не
 * безопасным. Ошибка в эту сторону стоит непереименованного тега, ошибка в
 * другую — испорченных данных в облаке.
 */
function isSafeToRewrite(t: Transaction): boolean {
  // Переводы переписывать МОЖНО: отправка правки без структурных изменений
  // теперь патчит строку из кэша на месте и не пересобирает ноги, так что
  // получатель и контрагент больше не теряются (`zenmoneyPush.ts`, ветка 0).
  // Долговые остаются в стороне: у них своя ветка, требующая плательщика.
  return t.category !== DEBT_LABEL && t.categoryFull !== DEBT_LABEL;
}

/**
 * Что именно произойдёт при переименовании — до того, как что-то записано.
 *
 * Чистая функция: её результат и показывается в окне подтверждения, и
 * превращается в патчи. Одно и то же вычисление на предпросмотр и на запись —
 * иначе предпросмотр однажды соврёт.
 */
export function planHashtagRename(
  transactions: Transaction[],
  from: string,
  to: string,
  /** Идентификаторы неотправленных черновиков — до них правки не доходят. */
  draftIds?: ReadonlySet<string>
): HashtagRenamePlan {
  const rows: HashtagRenameRow[] = [];
  const skipped = { debts: 0, drafts: 0 };
  let collapsed = 0;
  let isMerge = false;

  for (const t of transactions) {
    const tags = extractHashtags(t.comment);
    if (!tags.includes(from)) continue;
    if (draftIds?.has(t.id)) {
      skipped.drafts++;
      continue;
    }
    if (!isSafeToRewrite(t)) {
      skipped.debts++;
      continue;
    }
    const after = renameHashtagInComment(t.comment, from, to);
    if (after === t.comment) continue;
    if (tags.includes(to)) {
      isMerge = true;
      collapsed++;
    }
    rows.push({
      id: t.id,
      date: t.date,
      payee: t.payee || "",
      amountBase: t.amountBase,
      kind: t.kind,
      before: t.comment,
      after,
    });
  }

  // Перенос — это когда целевой тег существует и БЕЗ наших правок, даже если ни
  // в одном комментарии два тега не встретились рядом.
  if (!isMerge) {
    isMerge = transactions.some(
      (t) => isSafeToRewrite(t) && extractHashtags(t.comment).includes(to)
    );
  }

  return { rows, skipped, isMerge, collapsed };
}

/**
 * Правила категорий, которые упоминают тег.
 *
 * Нужно, потому что правило с действием «дописать в комментарий #налоги» вернёт
 * старый тег на следующем же прогоне правил, и переименование будет выглядеть
 * как не сработавшее. Молча так оставлять нельзя — предупреждаем.
 */
export function rulesMentioningHashtag(
  rules: { id: string; name?: string; [k: string]: unknown }[],
  hashtag: string
): string[] {
  const needle = `#${hashtag}`;
  const out: string[] = [];
  for (const rule of rules) {
    // Ищем по всему телу правила: условия и действия хранятся в разных
    // версиях схемы по-разному, а строковый поиск переживает обе.
    let blob: string;
    try {
      blob = JSON.stringify(rule);
    } catch {
      continue;
    }
    if (!blob.includes(needle)) continue;
    // Отсекаем частичное совпадение: «#налоги» не должен ловиться на «#налоги2».
    const re = new RegExp(
      `#${escapeForRegExp(hashtag)}(?![\\p{L}\\p{N}_-])`,
      "u"
    );
    if (re.test(blob)) out.push(String(rule.name || rule.id));
  }
  return out;
}

function escapeForRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
