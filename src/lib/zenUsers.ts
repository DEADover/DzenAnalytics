/**
 * Участники общего аккаунта Дзен-мани (issues #92, #95).
 *
 * ЧТО ПРОВЕРЕНО НА ЖИВОМ ОБЩЕМ АККАУНТЕ. Поле `user` у записей — НЕ «чей». Оно
 * одинаково у всех 34 счетов и всех 10 469 операций, включая заведённые с
 * дополнительного аккаунта: это владелец подписки. Различает участников
 * единственное поле — `role` у СЧЁТА:
 *
 *   • `null` — общий счёт, виден всем;
 *   • номер  — личный счёт этого участника.
 *
 * Личный счёт Дзен-мани прячет от остальных в приложении и на сайте, НО ПО API
 * ОТДАЁТ ВСЁ: токен дополнительного аккаунта получает и пятнадцать личных
 * счетов основного, и все операции по ним. Прячут только клиенты у себя —
 * отсюда и #95.
 *
 * КТО ТАКОЙ «Я» — ПО ОТВЕТУ API НЕ УЗНАТЬ. `user[]` у токенов разных участников
 * совпадает байт в байт; единственное найденное отличие — цвета категорий,
 * признак ненадёжный. Поэтому участника выбирает человек сам, а догадка
 * (`guessOwnerId`) годится только как подсказка: она всегда называет владельца
 * подписки, то есть для всех остальных ошибается.
 *
 * КАК ЗОВЁМ. Дзен-мани знает логин и почту. Почту не показываем: чужой адрес в
 * фильтре ни к чему. Остаётся логин, а поверх — псевдоним из настроек.
 */

import type { ZenDiffResponse } from "./zenmoney";

/** Один человек на аккаунте — ровно то, что нужно списку и фильтру. */
export interface ZenUserOption {
  id: number;
  /** Логин из Дзен-мани; `null`, если сервис его не прислал. */
  login: string | null;
  /** Номер основного пользователя — у дополнительных на общем аккаунте. */
  parent: number | null;
}

/** Псевдонимы: номер пользователя (строкой, как ключ) → как его звать. */
export type UserAliases = Record<string, string>;

/**
 * Как показать пользователя.
 *
 * Порядок: псевдоним → логин → номер. Номер — последнее средство, но лучше
 * пустоты: по нему хотя бы видно, что людей несколько и они разные.
 */
export function userLabel(
  id: number,
  users: ZenUserOption[],
  aliases: UserAliases = {}
): string {
  const alias = aliases[String(id)]?.trim();
  if (alias) return alias;
  const login = users.find((u) => u.id === id)?.login?.trim();
  if (login) return login;
  return `Пользователь ${id}`;
}

/**
 * Разобрать запись `user` из ответа Дзен-мани.
 *
 * Тип поля в API — «объект с `id` и чем угодно ещё», поэтому логин достаём
 * осторожно: он строка, если есть, и `null` во всех прочих случаях.
 */
export function zenUsers(raw: ZenDiffResponse["user"] | undefined): ZenUserOption[] {
  if (!raw) return [];
  return raw.map((u) => ({
    id: u.id,
    login: typeof u.login === "string" && u.login.trim() ? u.login.trim() : null,
    parent: typeof u.parent === "number" ? u.parent : null,
  }));
}

/**
 * Значение фильтра для операций на ОБЩИХ счетах.
 *
 * Общий счёт не принадлежит никому, и выбрасывать такие операции из выбора
 * нельзя: на общем аккаунте это обычно большая часть трат. Поэтому «Общие» —
 * отдельный пункт списка наравне с людьми.
 */
export const MEMBER_SHARED = "\u0000__shared__";

/**
 * Чьи личные счета встречаются в данных, по убыванию числа операций.
 *
 * Берём не список аккаунта, а тех, чьи операции у нас есть: участник мог не
 * завести ни одного личного счёта, и пустая строка в фильтре только мешает.
 * Порядок по частоте — чтобы самый заметный стоял первым; при равенстве по
 * номеру, чтобы список не прыгал между синхронизациями.
 */
export function membersInData(items: { member?: number | null }[]): number[] {
  const count = new Map<number, number>();
  for (const it of items) {
    if (it.member == null) continue;
    count.set(it.member, (count.get(it.member) ?? 0) + 1);
  }
  return [...count.entries()]
    .sort((a, b) => b[1] - a[1] || a[0] - b[0])
    .map(([id]) => id);
}

/** Есть ли в данных хоть один общий счёт — нужен ли пункт «Общие». */
export function hasSharedItems(items: { member?: number | null }[]): boolean {
  return items.some((it) => it.member == null);
}

/**
 * Подсказка, кто из участников — хозяин токена.
 *
 * ИМЕННО ПОДСКАЗКА, не ответ. Проверено на живом общем аккаунте: `user[]` у
 * токенов разных участников совпадает байт в байт, и по ответу API владельца
 * не отличить. Эта функция всегда назовёт владельца подписки — у него пуст
 * `parent`, — то есть для всех остальных участников соврёт.
 *
 * Поэтому она годится только чтобы подставить вероятный вариант в вопросе
 * «кто вы», и никогда — чтобы решить за человека. Всё, что зависит от ответа
 * (какие личные счета прятать, чьи планы показывать), включается ТОЛЬКО после
 * явного выбора: ошибка здесь стоит чужой приватности.
 */
export function likelyOwnerId(users: ZenUserOption[]): number | null {
  const root = users.find((u) => u.parent == null);
  return root?.id ?? users[0]?.id ?? null;
}
