import type { ReactNode } from "react";

/**
 * Ряд контролов раздела — между общим фильтром и итогами, ступень 42: всё,
 * что настраивает показанное ниже целиком. Сторона («Расходы / Доходы») или
 * вкладка — слева; разрез, год, период, бегунок, режим — справа или следом.
 *
 * Появляется, только если такие настройки у раздела есть. Прежде они жили где
 * придётся: в «Топе» — отдельным рядом, в «Категориях» и на «Счетах» — в шапке
 * страницы рядом с кнопками 34, в «Трендах» и «Календаре» — там же, но мелкой
 * ступенью, а бегунки «Аномалий», «Дубликатов» и «Облака слов» — в правом
 * углу шапки, через весь экран от того, что они меняют.
 */
export function SectionControls({ children }: { children: ReactNode }) {
  return <div className="flex flex-wrap items-center justify-between gap-3">{children}</div>;
}
