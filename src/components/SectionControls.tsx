import type { ReactNode } from "react";

/**
 * Ряд контролов раздела — между общим фильтром и итогами: сторона
 * («Расходы / Доходы») слева, разрез или вид справа, ступень 42.
 *
 * Появляется, только если раздел переключает содержимое целиком. Прежде такой
 * выбор жил где придётся: в «Топе» — отдельным рядом, в «Категориях» и на
 * «Счетах» — в шапке страницы рядом с кнопками 34, в «Трендах» и
 * «Календаре» — там же, но мелкой ступенью, а в «Категориях» ещё и внутри
 * карточки. Один и тот же смысл стоял в четырёх местах.
 */
export function SectionControls({ children }: { children: ReactNode }) {
  return <div className="flex flex-wrap items-center justify-between gap-3">{children}</div>;
}
